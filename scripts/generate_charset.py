def _encode(pattern: tuple[str, ...]) -> bytes:
    if len(pattern) != 7 or any(len(row) != 5 for row in pattern):
        raise ValueError("every glyph must be exactly 5x7")
    rows = []
    for row in pattern:
        value = 0
        for column, pixel in enumerate(row):
            if pixel == "1":
                value |= 1 << (6 - column)
            elif pixel != "0":
                raise ValueError(f"invalid pixel {pixel!r}")
        rows.append(value)
    return bytes((*rows, 0))


def build_charset() -> bytes:
    charset = bytearray(256 * 8)
    for character, pattern in FONT_5X7.items():
        glyph = _encode(pattern)
        # ACME !scr encodes this source's uppercase strings as PETSCII bytes.
        screen_code = ord(character)
        charset[screen_code * 8 : (screen_code + 1) * 8] = glyph
    return bytes(charset)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--output",
        type=Path,
        default=Path(__file__).resolve().parents[1] / "custom_charset_1bpp.bin",
    )
    args = parser.parse_args()

    generated = build_charset()
    if not args.output.exists() or args.output.read_bytes() != generated:
        args.output.write_bytes(generated)
    print(f"wrote {len(generated)} bytes to {args.output}")


if __name__ == "__main__":
    main()
